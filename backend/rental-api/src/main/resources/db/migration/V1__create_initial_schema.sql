CREATE TABLE buildings (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           name VARCHAR(150) NOT NULL,
                           address TEXT NOT NULL,
                           locality VARCHAR(100) NOT NULL,
                           city VARCHAR(100) NOT NULL DEFAULT 'Pune',
                           pincode VARCHAR(10),
                           description TEXT,
                           created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE flats (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       building_id BIGINT NOT NULL,
                       flat_number VARCHAR(20) NOT NULL,
                       floor_number INTEGER,
                       flat_type VARCHAR(50),
                       monthly_rent NUMERIC(10, 2) NOT NULL,
                       deposit NUMERIC(10, 2),
                       parking BOOLEAN NOT NULL DEFAULT FALSE,
                       status VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE',

                       CONSTRAINT fk_flat_building
                           FOREIGN KEY (building_id)
                               REFERENCES buildings(id),

                       CONSTRAINT uq_building_flat
                           UNIQUE (building_id, flat_number),

                       CONSTRAINT chk_flat_rent
                           CHECK (monthly_rent >= 0),

                       CONSTRAINT chk_flat_status
                           CHECK (status IN ('AVAILABLE', 'OCCUPIED', 'MAINTENANCE'))
);

CREATE INDEX idx_flats_building_id
    ON flats(building_id);